"""Typed, order-preserving lowering and compact Silver emission for a closed Java subset."""
from fractions import Fraction
from .model import *
from .frontend import Program

PLATFORM_CONSTANTS = {
    ('Integer','MAX_VALUE'): ('2147483647', INT),
    ('Integer','MIN_VALUE'): ('(-2147483648)', INT),
    ('Long','MAX_VALUE'): ('9223372036854775807', JType('long')),
    ('Long','MIN_VALUE'): ('(-9223372036854775808)', JType('long')),
}


def indent(lines): return ['  '+s for s in lines]


class Compiler:
    def __init__(self,sources,spec=None):
        self.program=Program(sources);self.spec=spec or {}
        self.validate_spec()
        self.fields={};self.runtime=set();self.maps={'methods':{},'loops':{}}
        self.notes=set();self.used_specs=set()
        for c in self.program.classes.values():
            for f in c.fields.values():
                if not f.static:self.fields[f.silver]=f.typ.silver
                elif not f.final:
                    self.program.fail('Mutable static fields are not implemented; use explicit instance state',c.node)

    def validate_spec(self):
        if not isinstance(self.spec,dict) or set(self.spec)-{'methods','loops','definitions'}:
            raise TranslationError('Specification accepts only methods, loops, and trusted definitions')
        definitions=self.spec.get('definitions',[])
        if not isinstance(definitions,list) or not all(isinstance(x,str) and x.strip() for x in definitions):
            raise TranslationError('definitions must be a list of nonempty Silver declarations')
        for section,allowed in [('methods',{'requires','ensures'}),('loops',{'invariants','decreases'})]:
            entries=self.spec.get(section,{})
            if not isinstance(entries,dict):raise TranslationError(section+' must be an object')
            for key,cfg in entries.items():
                if not isinstance(cfg,dict) or set(cfg)-allowed:raise TranslationError('Invalid specification fields at '+key)
                for field,items in cfg.items():
                    if not isinstance(items,list) or not all(isinstance(s,str) and s.strip() for s in items):
                        raise TranslationError(key+'.'+field+' must be a list of nonempty Silver expressions')

    def compile(self):
        methods=[]
        for c in self.program.classes.values():
            for m in c.methods.values():methods += self.method(m)+['']
        unknown=set(self.spec.get('methods',{}))-set(self.program.methods)
        if unknown:raise TranslationError('Unknown methods in specification: '+', '.join(sorted(unknown)))
        unknown=set(self.spec.get('loops',{}))-set(self.maps['loops'])
        if unknown:raise TranslationError('Unknown loops in specification: '+', '.join(sorted(unknown)))
        header=['// Generated by java-silver-framework; mathematical integers/reals.',
                '// Fixed contracts/proofs come from the explicit specification file.']
        header += [f'field {k}: {v}' for k,v in sorted(self.fields.items())]
        code='\n'.join(header+['']+self.helpers()+self.spec.get('definitions',[])+['']+methods).rstrip()+'\n'
        for key,item in self.maps['loops'].items():
            marker='// loop '+key
            item['silver_line']=next(i for i,l in enumerate(code.splitlines(),1) if marker in l)
        self.maps.update({'notes':sorted(self.notes),'semantics':{'integer':'mathematical','float':'mathematical_real'},
                          'has_external_goal':any(v.get('ensures') for v in self.spec.get('methods',{}).values()),
                          'source_assert_count':sum(n.type=='assert_statement' for _,_,tree in self.program.sources for n in walk(tree.root_node)),
                          'status':'translated_not_a_correctness_verdict'})
        return code,self.maps

    def fail(self,message,node):self.program.fail(message,node)
    def fresh(self,typ,pre,value=None):
        name=f'_j_t{self.counter}';self.counter+=1
        pre.append(f'var {name}: {typ.silver}')
        if value is not None:pre.append(f'{name} := {value}')
        return name
    def field(self,t):
        if not t.dims:raise ValueError('array expected')
        self.fields[t.field]='Seq['+t.element.silver+']'
        return t.field
    def freeze(self,e,pre):
        pre.extend(e.pre)
        return self.fresh(e.typ,pre,e.value)
    def compatible(self,a,b):
        return a==b or (a.ref and b==NULL) or (a.real and b.integer) or (a.integer and b.integer and (a.base!='char' or b.base=='char'))
    def convert(self,e,t,node):
        if not self.compatible(t,e.typ):self.fail(f'Type mismatch: expected {t}, got {e.typ}',node)
        return f'({e.value} * write)' if t.real and e.typ.integer else e.value
    def local(self,name,t,node):
        if any(name in s for s in self.scopes):self.fail('Overlapping local declaration '+name,node)
        v=safe(name)
        if v in self.names:v=f'{v}_{self.counter}';self.counter+=1
        self.names.add(v);self.scopes[-1][name]=(v,t)
        return v
    def lookup(self,name):
        for scope in reversed(self.scopes):
            if name in scope:return scope[name]
        return None

    def method(self,m):
        self.current=m;self.owner=self.program.classes[m.owner]
        self.counter=0;self.loop_count=0;self.loop_stack=[];self.scopes=[{}];self.names=set();self.assigned=set()
        self.return_label='_j_return';self.constant_stack=set()
        params=[];body=[];req=[];ens=[]
        if not m.static:
            params.append('self: Ref');self.names.add('self');req.append('self != null')
        written={txt(n.child_by_field_name('left')) for n in walk(m.node) if n.type=='assignment_expression'}
        written.update(txt(children(n)[0]) for n in walk(m.node) if n.type=='update_expression')
        for name,t in m.parameters:
            v=self.local(name,t,m.node)
            self.assigned.add(v)
            if name in written:
                arg='_j_in_'+v;params.append(arg+': '+t.silver);body += [f'var {v}: {t.silver}',f'{v} := {arg}']
            else:params.append(v+': '+t.silver)
        cfg=self.spec.get('methods',{}).get(m.key,{})
        req+=cfg.get('requires',[]);ens+=cfg.get('ensures',[])
        if m.constructor:
            for f in self.owner.fields.values():
                if not f.static:
                    req.append(f'acc(self.{f.silver})');ens.append(f'acc(self.{f.silver})')
        self.maps['methods'][m.key]={'silver_name':m.silver,'source_line':m.node.start_point.row+1,
                                      'source_name':m.name,'arity':len(m.parameters),
                                      'parameters':[{'name':n,'java_type':str(t),'silver_name':self.lookup(n)[0],
                                                     'input_name':('_j_in_' if n in written else '')+self.lookup(n)[0]} for n,t in m.parameters]}
        body+=self.stmt(m.node.child_by_field_name('body'))
        if m.typ!=VOID and self.falls_through(m.node.child_by_field_name('body')):
            self.fail('Non-void method may fall through without returning a value',m.node)
        if any(self.return_label in l for l in body):body.append('label '+self.return_label)
        sig=f'method {m.silver}('+', '.join(params)+')'
        if m.typ!=VOID:sig+=' returns (res: '+m.typ.silver+')'
        return [sig]+['  requires '+x for x in req]+['  ensures '+x for x in ens]+['{']+indent(body)+['}']

    def lvalue(self,node,capture=True):
        k=node.type
        if k=='identifier':
            name=txt(node);local=self.lookup(name)
            if local:return LValue(local[0],local[1])
            f=self.owner.fields.get(name)
            if f and not f.static:
                if self.current.static:self.fail('Instance field in static context',node)
                return LValue('self.'+f.silver,f.typ)
            self.fail('Unknown/immutable assignment target '+name,node)
        if k=='array_access':
            a=self.expr(node.child_by_field_name('array'));idx=self.expr(node.child_by_field_name('index'))
            if not a.typ.dims or not idx.typ.integer:self.fail('Array access needs array and integer index',node)
            pre=[]
            av=self.freeze(a,pre) if capture else a.value
            if not capture:pre+=a.pre
            iv=self.freeze(idx,pre) if capture else idx.value
            if not capture:pre+=idx.pre
            f=self.field(a.typ)
            return LValue(f'{av}.{f}[{iv}]',a.typ.element,pre,av,iv,f)
        if k=='field_access':
            obj=self.expr(node.child_by_field_name('object'));name=txt(node.child_by_field_name('field'))
            if obj.typ.dims or obj.typ.base not in self.program.classes:self.fail('Unknown object field '+name,node)
            f=self.program.classes[obj.typ.base].fields.get(name)
            if not f or f.static or f.final:self.fail('Unknown or immutable field '+name,node)
            pre=[];ov=self.freeze(obj,pre) if capture else obj.value
            if not capture:pre+=obj.pre
            return LValue(ov+'.'+f.silver,f.typ,pre)
        self.fail('Unsupported assignment target '+k,node)

    def expr(self,n,expected=None):
        k=n.type;s=txt(n)
        if k=='parenthesized_expression':return self.expr(children(n)[0],expected)
        if k in {'decimal_integer_literal','hex_integer_literal','octal_integer_literal','binary_integer_literal'}:
            v=s.replace('_','').rstrip('lL');base=16 if v.lower().startswith('0x') else 2 if v.lower().startswith('0b') else 8 if len(v)>1 and v.startswith('0') else 10
            value=int(v,base);bits=64 if s[-1:] in 'lL' else 32
            if base!=10 and value >= 2**(bits-1):
                if value>=2**bits:self.fail('Integer literal exceeds Java width',n)
                value-=2**bits
            return Expr(str(value),JType('long') if s[-1:] in 'lL' else INT)
        if k in {'decimal_floating_point_literal','hex_floating_point_literal'}:
            if k.startswith('hex'):self.fail('Hex floating literals not implemented',n)
            f=Fraction(s.replace('_','').rstrip('fFdD'))
            return Expr(f'({f.numerator} * write / {f.denominator})',REAL)
        if k=='character_literal':
            value=self.quoted(s,n)
            raw=value.encode('utf-16-le','surrogatepass')
            if len(raw)!=2:self.fail('A Java char must be one UTF-16 code unit',n)
            return Expr(str(int.from_bytes(raw,'little')),JType('char'))
        if k=='string_literal':
            value=self.quoted(s,n)
            units=value.encode('utf-16-le','surrogatepass')
            vals=[str(int.from_bytes(units[i:i+2],'little')) for i in range(0,len(units),2)]
            return self.make_string('Seq('+', '.join(vals)+')' if vals else 'Seq[Int]()',[],n)
        if k in {'true','false'}:return Expr(s,BOOL)
        if k=='null_literal':return Expr('null',NULL)
        if k=='this':
            if self.current.static:self.fail('this in static context',n)
            return Expr('self',JType(self.current.owner))
        if k=='identifier':
            v=self.lookup(s)
            if v:
                if v[0] not in self.assigned:self.fail('Local may be uninitialized: '+s,n)
                return Expr(v[0],v[1])
            f=self.owner.fields.get(s)
            if f:
                if f.static:return self.constant(f,n)
                if self.current.static:self.fail('Instance field in static context',n)
                return Expr('self.'+f.silver,f.typ)
            self.fail('Unresolved variable '+s,n)
        if k=='field_access':
            objnode=n.child_by_field_name('object');name=txt(n.child_by_field_name('field'));owner=txt(objnode)
            if (owner,name) in PLATFORM_CONSTANTS:
                value,typ=PLATFORM_CONSTANTS[(owner,name)]
                return Expr(value,typ)
            if owner in self.program.classes and name in self.program.classes[owner].fields:
                f=self.program.classes[owner].fields[name]
                if f.static:return self.constant(f,n)
            obj=self.expr(objnode)
            if obj.typ.dims and name=='length':return Expr(f'|{obj.value}.{self.field(obj.typ)}|',INT,obj.pre)
            lv=self.lvalue(n,False);return Expr(lv.value,lv.typ,lv.pre)
        if k=='array_access':
            a=self.expr(n.child_by_field_name('array'));idx=self.expr(n.child_by_field_name('index'))
            if not a.typ.dims or not idx.typ.integer:self.fail('Invalid array/index types',n)
            pre=[];av=self.freeze(a,pre) if idx.pre else a.value
            if not idx.pre:pre+=a.pre
            pre+=idx.pre
            return Expr(f'{av}.{self.field(a.typ)}[{idx.value}]',a.typ.element,pre)
        if k=='binary_expression':return self.binary(n)
        if k=='unary_expression':
            e=self.expr(n.child_by_field_name('operand'));op=txt(n.child_by_field_name('operator'))
            if op=='!' and e.typ==BOOL:return Expr(f'!({e.value})',BOOL,e.pre)
            if op in {'+','-'} and (e.typ.integer or e.typ.real):return Expr(f'({op}{e.value})',REAL if e.typ.real else INT,e.pre)
            self.fail('Unsupported unary operator/types '+op,n)
        if k=='ternary_expression':
            c=self.expr(n.child_by_field_name('condition'));before=set(self.assigned)
            a=self.expr(n.child_by_field_name('consequence'),expected);yes=set(self.assigned);self.assigned=set(before)
            b=self.expr(n.child_by_field_name('alternative'),expected);self.assigned &= yes
            if c.typ!=BOOL:self.fail('Condition must be boolean',n)
            t=expected or (REAL if a.typ.real or b.typ.real else b.typ if a.typ==NULL else a.typ)
            av=self.convert(a,t,n);bv=self.convert(b,t,n)
            if not a.pre and not b.pre:return Expr(f'({c.value} ? {av} : {bv})',t,c.pre)
            pre=list(c.pre);v=self.fresh(t,pre)
            pre += [f'if ({c.value}) {{']+indent(a.pre+[f'{v} := {av}'])+['} else {']+indent(b.pre+[f'{v} := {bv}'])+['}']
            return Expr(v,t,pre)
        if k in {'update_expression','assignment_expression'}:
            target=children(n)[0] if k=='update_expression' else n.child_by_field_name('left')
            lv=self.lvalue(target);pre=list(lv.pre)
            if k=='update_expression':
                if target.type=='identifier' and self.lookup(txt(target)) and lv.value not in self.assigned:self.fail('Increment of uninitialized local',n)
                if lv.typ.base=='char':self.fail('char increment/narrowing not supported',n)
                if not (lv.typ.integer or lv.typ.real):self.fail('Increment needs numeric lvalue',n)
                old=self.fresh(lv.typ,pre,lv.value);step='write' if lv.typ.real else '1'
                op='+' if '++' in s else '-';value=self.fresh(lv.typ,pre,f'{old} {op} {step}');pre.append(lv.store(value))
                return Expr(value if s.startswith(('++','--')) else old,lv.typ,pre)
            op=txt(n.child_by_field_name('operator'));rhs=self.expr(n.child_by_field_name('right'),lv.typ)
            if op!='=':
                if target.type=='identifier' and self.lookup(txt(target)) and lv.value not in self.assigned:self.fail('Compound assignment reads uninitialized local',n)
                old=self.fresh(lv.typ,pre,lv.value)
                r=self.operation(Expr(old,lv.typ),rhs,op[:-1],n)
                pre+=r.pre;value=self.convert(r,lv.typ,n)
            else:pre+=rhs.pre;value=self.convert(rhs,lv.typ,n)
            v=self.fresh(lv.typ,pre,value);pre.append(lv.store(v))
            if target.type=='identifier' and self.lookup(txt(target)):self.assigned.add(lv.value)
            return Expr(v,lv.typ,pre)
        if k=='array_creation_expression':return self.array_new(n)
        if k=='array_initializer':
            if expected is None or not expected.dims:self.fail('Array initializer needs declared array type',n)
            pre=[];values=[]
            for ch in children(n):
                e=self.expr(ch,expected.element);v=self.freeze(e,pre);values.append(self.convert(Expr(v,e.typ),expected.element,ch))
            a=self.fresh(expected,pre);f=self.field(expected)
            pre += [f'{a} := new({f})',f'{a}.{f} := '+('Seq('+', '.join(values)+')' if values else f'Seq[{expected.element.silver}]()')]
            return Expr(a,expected,pre)
        if k=='object_creation_expression':return self.object_new(n)
        if k=='method_invocation':return self.call(n)
        if k=='cast_expression':
            t=parse_type(n.child_by_field_name('type'));e=self.expr(n.child_by_field_name('value'))
            if t.integer and e.typ.integer and t.base!='char':return Expr(e.value,t,e.pre)
            if t.real and (e.typ.integer or e.typ.real):return Expr(self.convert(e,t,n),t,e.pre)
            self.fail('Narrowing/reference/real-to-int casts unsupported',n)
        self.fail('Unsupported expression: '+k,n)

    def quoted(self,s,node):
        value=[];i=1;end=len(s)-1
        escapes={'b':'\b','t':'\t','n':'\n','f':'\f','r':'\r','s':' ','"':'"',"'":"'",'\\':'\\'}
        while i<end:
            ch=s[i];i+=1
            if ch!='\\':value.append(ch);continue
            if i>=end:self.fail('Incomplete Java literal escape',node)
            ch=s[i];i+=1
            if ch in escapes:value.append(escapes[ch])
            elif ch in '01234567':
                digits=ch;limit=3 if ch in '0123' else 2
                while len(digits)<limit and i<end and s[i] in '01234567':digits+=s[i];i+=1
                value.append(chr(int(digits,8)))
            else:self.fail('Unsupported Java literal escape: '+ch,node)
        return ''.join(value)

    def constant(self,f,node):
        if not f.final or f.value is None or not (f.typ.integer or f.typ.real or f.typ==BOOL):self.fail('Only scalar static final constants supported',node)
        if f.silver in self.constant_stack:self.fail('Cyclic static initializer',node)
        def check(n):
            if n.type=='field_access':
                owner=txt(n.child_by_field_name('object'));name=txt(n.child_by_field_name('field'))
                if (owner,name) in PLATFORM_CONSTANTS and owner not in self.program.classes[f.owner].fields:
                    return
                self.fail('Unsupported reference in static constant initializer',n)
            if n.type in {'identifier','method_invocation','update_expression','assignment_expression','object_creation_expression'}:
                self.fail('Static initializer supports literals and platform constants only',n)
            for child in children(n):check(child)
        check(f.value)
        self.constant_stack.add(f.silver);e=self.expr(f.value);self.constant_stack.remove(f.silver)
        return Expr(self.convert(e,f.typ,node),f.typ,e.pre)

    def binary(self,n):
        a=self.expr(n.child_by_field_name('left'));before=set(self.assigned)
        b=self.expr(n.child_by_field_name('right'));op=txt(n.child_by_field_name('operator'))
        if op in {'&&','||'}:
            self.assigned=before
            if a.typ!=BOOL or b.typ!=BOOL:self.fail('Boolean operands required',n)
            if not b.pre:return Expr(f'({a.value} {op} {b.value})',BOOL,a.pre)
            pre=list(a.pre);v=self.fresh(BOOL,pre,a.value)
            pre+=[f'if ({v if op=="&&" else "!"+v}) {{']+indent(b.pre+[f'{v} := {b.value}'])+['}']
            return Expr(v,BOOL,pre)
        pre=[];av=self.freeze(a,pre) if b.pre else a.value
        if not b.pre:pre+=a.pre
        pre+=b.pre
        e=self.operation(Expr(av,a.typ),Expr(b.value,b.typ),op,n)
        return Expr(e.value,e.typ,pre+e.pre)

    def operation(self,a,b,op,n):
        pre=a.pre+b.pre
        if op=='+' and (a.typ==STRING or b.typ==STRING):
            if a.typ==STRING and b.typ.base=='char' and not b.typ.dims:
                self.fields['str_chars']='Seq[Int]'
                contents=f'({a.value} == null ? Seq(110, 117, 108, 108) : {a.value}.str_chars)'
                return self.make_string(f'{contents} ++ Seq({b.value})',pre,n)
            self.fail('Only String + char concatenation implemented',n)
        if op in {'==','!='}:
            if a.typ==STRING and b.typ==STRING:self.fail('String identity/intern observations not supported',n)
            if a.typ.ref and b.typ.ref:
                if a.typ!=b.typ and a.typ!=NULL and b.typ!=NULL:self.fail('Incompatible reference comparison',n)
                return Expr(f'({a.value} {op} {b.value})',BOOL,pre)
            if a.typ==BOOL and b.typ==BOOL:return Expr(f'({a.value} {op} {b.value})',BOOL,pre)
        if op in {'&','|','^'} and a.typ==b.typ==BOOL:
            av=self.fresh(BOOL,pre,a.value);bv=self.fresh(BOOL,pre,b.value)
            return Expr(f'({av} '+{'&':'&&','|':'||','^':'!='}[op]+f' {bv})',BOOL,pre)
        if op=='&' and a.typ.integer and b.typ.integer and b.value=='1':
            self.runtime.add('division');return Expr(f'(jrem({a.value}, 2) != 0 ? 1 : 0)',INT,pre)
        if not (a.typ.integer or a.typ.real) or not (b.typ.integer or b.typ.real):self.fail('Incompatible operands for '+op,n)
        t=REAL if a.typ.real or b.typ.real else INT
        av=self.convert(a,t,n);bv=self.convert(b,t,n)
        if op in {'+','-','*'}:return Expr(f'({av} {op} {bv})',t,pre)
        if op in {'<','<=','>','>=','==','!='}:return Expr(f'({av} {op} {bv})',BOOL,pre)
        if op in {'/','%'} and t==INT:
            self.runtime.add('division');return Expr(f'{"jdiv" if op=="/" else "jrem"}({av}, {bv})',INT,pre)
        if op=='/' and t==REAL:
            right=n.child_by_field_name('right')
            try:d=Fraction(txt(right).replace('_','').rstrip('dDfF'))
            except (ValueError,ZeroDivisionError):self.fail('Only literal nonzero real divisors supported',n)
            if d==0:self.fail('Real division by zero',n)
            return Expr(f'({av} * ({d.denominator} * write / {d.numerator}))',REAL,pre)
        self.fail('Unsupported numeric operator '+op,n)

    def make_string(self,value,pre,node):
        self.fields['str_chars']='Seq[Int]';pre=list(pre)
        # Evaluate contents before allocation/field write; all supported observations are content-based.
        name=self.fresh(STRING,pre);pre += [f'{name} := new(str_chars)',f'{name}.str_chars := {value}']
        self.notes.add('String literals/concatenations use fresh content objects; identity/intern comparisons are rejected.')
        return Expr(name,STRING,pre)

    def array_new(self,n):
        base=parse_type(n.child_by_field_name('type'))
        sizes=[];pre=[];missing=0
        initializer=next((x for x in children(n) if x.type=='array_initializer'),None)
        for ch in children(n):
            if ch.type=='dimensions_expr':
                e=self.expr(children(ch)[0])
                if not e.typ.integer:self.fail('Array dimension must be integer',ch)
                sizes.append(e.value if not e.pre and e.value.isdigit() else self.freeze(e,pre))
            elif ch.type=='dimensions':missing+=txt(ch).count('[')
        t=JType(base.base,len(sizes)+missing)
        if initializer:return self.expr(initializer,t)
        if not sizes:self.fail('Array allocation has no dimension',n)
        if len(sizes)>3:self.fail('More than three supplied array dimensions are outside the first subset',n)
        pre += [f'assert {s} >= 0' for s in sizes]
        value=self.allocate(t,sizes,pre,n)
        return Expr(value,t,pre)

    def allocate(self,t,sizes,pre,node):
        f=self.field(t);a=self.fresh(t,pre)
        pre.append(f'{a} := new({f})')
        small=sizes[0].isdigit() and int(sizes[0])<=8
        if small:
            initial='Seq('+', '.join([t.element.default]*int(sizes[0]))+')' if int(sizes[0]) else f'Seq[{t.element.silver}]()'
            pre.append(f'{a}.{f} := {initial}')
        else:
            seq=f'_j_s{self.counter}';self.counter+=1
            pre += [f'var {seq}: Seq[{t.element.silver}]',f'inhale |{seq}| == {sizes[0]}',
                    f'inhale forall _j_q: Int :: 0 <= _j_q && _j_q < {sizes[0]} ==> {seq}[_j_q] == {t.element.default}',f'{a}.{f} := {seq}']
        if len(sizes)>1:
            if small:
                for index in range(int(sizes[0])):
                    row=self.allocate(t.element,sizes[1:],pre,node)
                    pre.append(f'{a}.{f} := {a}.{f}[{index} := {row}]')
                return a
            i=self.fresh(INT,pre,'0');child=self.field(t.element)
            body=[];row=self.allocate(t.element,sizes[1:],body,node)
            body += [f'{a}.{f} := {a}.{f}[{i} := {row}]',f'{i} := {i} + 1']
            inv=[f'acc({a}.{f}) && |{a}.{f}| == {sizes[0]}',f'0 <= {i} && {i} <= {sizes[0]}',
                 f'forall _j_r: Ref :: _j_r in {a}.{f}[..{i}] ==> acc(_j_r.{child})',
                 f'forall _j_q: Int :: 0 <= _j_q && _j_q < {i} ==> |{a}.{f}[_j_q].{child}| == {sizes[1]}']
            if len(sizes)==2:
                inv += [f'forall _j_q: Int, _j_k: Int :: 0 <= _j_q && _j_q < {i} && 0 <= _j_k && _j_k < {sizes[1]} ==> {a}.{f}[_j_q].{child}[_j_k] == {t.element.element.default}']
            else:self.fail('Allocations with more than two supplied dimensions not yet implemented',node)
            inv += [f'forall _j_q: Int, _j_k: Int :: 0 <= _j_q && _j_q < _j_k && _j_k < {i} ==> {a}.{f}[_j_q] != {a}.{f}[_j_k]']
            pre += [f'while ({i} < {sizes[0]})']+['  invariant '+x for x in inv]+['{']+indent(body)+['}']
        return a

    def object_new(self,n):
        name=txt(n.child_by_field_name('type')).split('.')[-1]
        args=[self.expr(a) for a in children(n.child_by_field_name('arguments'))]
        pre=[];values=[self.freeze(a,pre) for a in args]
        if name=='Random':
            if args:self.fail('Seeded Random not supported',n)
            v=self.fresh(JType(name),pre);pre.append(f'{v} := new()');return Expr(v,JType(name),pre)
        if name not in self.program.classes:self.fail('Unknown constructor '+name,n)
        c=self.program.classes[name];fields=[f for f in c.fields.values() if not f.static]
        obj=self.fresh(JType(name),pre);pre.append(f'{obj} := new('+', '.join(f.silver for f in fields)+')')
        for f in fields:pre.append(f'{obj}.{f.silver} := {f.typ.default}')
        for f in fields:
            if f.value is not None:
                if any(x.type in {'this','identifier','method_invocation'} for x in walk(f.value)):
                    self.fail('Instance initializer using context/calls not implemented',f.value)
                val=self.expr(f.value,f.typ);pre+=val.pre+[f'{obj}.{f.silver} := {self.convert(val,f.typ,n)}']
        ctor=c.resolve_method(name,len(args))
        if ctor:
            if len(args)!=len(ctor.parameters):self.fail('Constructor arity mismatch',n)
            actual=[self.convert(Expr(v,a.typ),t,n) for v,a,(_,t) in zip(values,args,ctor.parameters)]
            pre.append(f'{ctor.silver}('+', '.join([obj]+actual)+')')
        elif args or any(m.constructor for m in c.methods.values()):self.fail('Constructor arity mismatch',n)
        return Expr(obj,JType(name),pre)

    def call(self,n):
        name=txt(n.child_by_field_name('name'));obj=n.child_by_field_name('object');owner=txt(obj)
        argnodes=children(n.child_by_field_name('arguments'))
        if owner in {'Verifier','org.sosy_lab.sv_benchmarks.Verifier'}:
            if name=='assume' and len(argnodes)==1:
                a=self.expr(argnodes[0])
                if a.typ!=BOOL:self.fail('assume expects boolean',n)
                self.notes.add('Source Verifier.assume is preserved as inhale.')
                return Expr('',VOID,a.pre+[f'inhale {a.value}'])
            types={'nondetInt':INT,'nondetLong':JType('long'),'nondetBoolean':BOOL,'nondetDouble':REAL,'nondetFloat':REAL}
            if name not in types or argnodes:self.fail('Unsupported Verifier API '+name,n)
            return self.nondet(types[name],[])
        if owner=='System' and name=='arraycopy':return self.arraycopy(argnodes,n)
        if owner=='Arrays':self.fail('Arrays.'+name+' needs a separately validated library model; not implemented',n)
        if owner in {'System.out','System.err'}:self.fail('Printing requires an explicit environment model; not silently removed',n)
        if owner=='Math' and name in {'min','max','abs'}:
            args=[self.expr(x) for x in argnodes];pre=[];vs=[self.freeze(a,pre) for a in args]
            if any(not(a.typ.integer or a.typ.real) for a in args):self.fail('Math requires numeric arguments',n)
            t=REAL if any(a.typ.real for a in args) else INT;vs=[self.convert(Expr(v,a.typ),t,n) for v,a in zip(vs,args)]
            if name=='abs' and len(args)==1:return Expr(f'({vs[0]} < {"none" if t==REAL else "0"} ? -{vs[0]} : {vs[0]})',t,pre)
            if name in {'min','max'} and len(args)==2:return Expr(f'({vs[0]} {"<" if name=="min" else ">"} {vs[1]} ? {vs[0]} : {vs[1]})',t,pre)
            self.fail('Math arity mismatch',n)
        pre=[];recv=None;args=None
        if obj is not None and owner not in self.program.classes:
            e=self.expr(obj)
            if e.typ==STRING:
                args=[self.expr(x) for x in argnodes]
                if not any(a.pre for a in args):
                    return self.string_call(Expr(e.value,e.typ),name,args,list(e.pre),n)
            recv=Expr(self.freeze(e,pre),e.typ)
        if args is None:args=[self.expr(x) for x in argnodes]
        vals=[self.freeze(a,pre) for a in args]
        args=[Expr(v,a.typ) for v,a in zip(vals,args)]
        if recv and recv.typ==STRING:return self.string_call(recv,name,args,pre,n)
        if recv and recv.typ.base=='Random':
            pre.append(f'assert {recv.value} != null')
            if name=='nextInt' and not args:return self.nondet(INT,pre)
            if name=='nextBoolean' and not args:return self.nondet(BOOL,pre)
            self.fail('Only unbounded Random.nextInt/nextBoolean supported',n)
        cname=recv.typ.base if recv else owner or self.current.owner
        if cname not in self.program.classes:self.fail('Unmodeled library call '+owner+'.'+name,n)
        method=self.program.classes[cname].resolve_method(name,len(args))
        if not method or method.constructor:self.fail('Unresolved method '+cname+'.'+name,n)
        if len(args)!=len(method.parameters):self.fail('Method arity mismatch',n)
        actual=[self.convert(a,t,n) for a,(_,t) in zip(args,method.parameters)]
        if not method.static:
            if recv:actual.insert(0,recv.value);pre.append(f'assert {recv.value} != null')
            elif not obj and not self.current.static:actual.insert(0,'self')
            else:self.fail('Instance method needs a receiver',n)
        call=method.silver+'('+', '.join(actual)+')'
        if method.typ==VOID:return Expr('',VOID,pre+[call])
        v=self.fresh(method.typ,pre);pre.append(f'{v} := {call}');return Expr(v,method.typ,pre)

    def nondet(self,t,pre):
        self.runtime.add('nd_'+t.silver);pre=list(pre);v=self.fresh(t,pre)
        pre.append(f'{v} := nondet{t.silver}()')
        self.notes.add('nondet is a trusted source-environment primitive; integer results are unbounded.')
        return Expr(v,t,pre)

    def string_call(self,recv,name,args,pre,n):
        self.fields['str_chars']='Seq[Int]';s=recv.value+'.str_chars';pre=list(pre)
        if name=='length' and not args:return Expr(f'|{s}|',INT,pre)
        if name=='charAt' and len(args)==1 and args[0].typ.integer:return Expr(f'{s}[{args[0].value}]',JType('char'),pre)
        if name=='equals' and len(args)==1 and args[0].typ in {STRING,NULL}:
            self.runtime.add('nonnull')
            value='false' if args[0].typ==NULL else f'({args[0].value} != null && {s} == {args[0].value}.str_chars)'
            return Expr(f'(jnonnull({recv.value}) && {value})',BOOL,pre)
        if name in {'startsWith','endsWith'} and 1<=len(args)<=2 and args[0].typ==STRING:
            if name=='endsWith' and len(args)!=1:self.fail('endsWith arity',n)
            if len(args)==2 and not args[1].typ.integer:self.fail('Prefix offset must be integer',n)
            p=args[0].value+'.str_chars';off=args[1].value if len(args)==2 else '0' if name=='startsWith' else f'(|{s}| - |{p}|)'
            self.runtime.add('nonnull')
            return Expr(f'(jnonnull({recv.value}) && jnonnull({args[0].value}) && 0 <= {off} && {off} + |{p}| <= |{s}| && {s}[{off}..{off} + |{p}|] == {p})',BOOL,pre)
        if name=='toCharArray' and not args:
            t=JType('char',1);f=self.field(t);v=self.fresh(t,pre)
            pre += [f'{v} := new({f})',f'{v}.{f} := {s}'];return Expr(v,t,pre)
        if name=='getChars' and len(args)==4 and args[2].typ==JType('char',1) and all(args[i].typ.integer for i in [0,1,3]):
            a,b,dst,off=[x.value for x in args];f=self.field(args[2].typ)
            pre += [f'assert 0 <= {a} && {a} <= {b} && {b} <= |{s}|',f'assert 0 <= {off} && {off} + {b} - {a} <= |{dst}.{f}|',
                    f'{dst}.{f} := {dst}.{f}[..{off}] ++ {s}[{a}..{b}] ++ {dst}.{f}[{off} + {b} - {a}..]']
            return Expr('',VOID,pre)
        self.fail('Unsupported String method '+name,n)

    def arraycopy(self,nodes,node):
        if len(nodes)!=5:self.fail('arraycopy arity',node)
        args=[self.expr(x) for x in nodes];pre=[];v=[self.freeze(a,pre) for a in args]
        if args[0].typ!=args[2].typ or args[0].typ not in {JType('int',1),JType('char',1),JType('double',1),JType('float',1),JType('long',1)} or not all(args[i].typ.integer for i in [1,3,4]):self.fail('Only matching primitive arraycopy supported',node)
        src,sp,dst,dp,count=v;f=self.field(args[0].typ)
        pre += [f'assert {src} != null && {dst} != null',f'assert 0 <= {sp} && 0 <= {dp} && 0 <= {count}',
                f'assert {sp} + {count} <= |{src}.{f}| && {dp} + {count} <= |{dst}.{f}|']
        snap=f'_j_s{self.counter}';self.counter+=1
        pre += [f'var {snap}: Seq[{args[0].typ.element.silver}]',f'{snap} := {src}.{f}',
                f'{dst}.{f} := {dst}.{f}[..{dp}] ++ {snap}[{sp}..{sp}+{count}] ++ {dst}.{f}[{dp}+{count}..]']
        return Expr('',VOID,pre)

    def stmt(self,n):
        k=n.type
        if k in {'block','constructor_body'}:
            self.scopes.append({});out=[]
            for c in children(n):out+=self.stmt(c)
            self.scopes.pop();return out
        if k=='local_variable_declaration':
            out=[]
            for d in children(n):
                if d.type!='variable_declarator':continue
                t=parse_type(n.child_by_field_name('type'),txt(d.child_by_field_name('dimensions')).count('[]'))
                if t.base not in set(self.program.classes)|{'String','Random','int','long','char','boolean','float','double'}:self.fail('Unknown local type '+str(t),n)
                value=d.child_by_field_name('value');e=self.expr(value,t) if value else None
                v=self.local(txt(d.child_by_field_name('name')),t,d);out.append(f'var {v}: {t.silver}')
                if e:out+=e.pre+[f'{v} := {self.convert(e,t,d)}'];self.assigned.add(v)
            return out
        if k=='expression_statement':
            return self.statement_expr(children(n)[0])
        if k=='if_statement':
            c=self.expr(n.child_by_field_name('condition'))
            if c.typ!=BOOL:self.fail('if condition must be boolean',n)
            before=set(self.assigned)
            out=c.pre+[f'if ({c.value}) {{']+indent(self.stmt(n.child_by_field_name('consequence')))+['}']
            yes=set(self.assigned);self.assigned=set(before)
            alt=n.child_by_field_name('alternative')
            if alt:out[-1]='} else {';out+=indent(self.stmt(alt))+['}']
            self.assigned &= yes
            return out
        if k in {'while_statement','for_statement','do_statement','enhanced_for_statement'}:return self.loop(n)
        if k=='return_statement':
            c=children(n)
            if self.current.typ==VOID:
                if c:self.fail('Value returned from void method',n)
                return ['goto '+self.return_label]
            if not c:self.fail('Missing return value',n)
            e=self.expr(c[0],self.current.typ)
            return e.pre+[f'res := {self.convert(e,self.current.typ,n)}','goto '+self.return_label]
        if k in {'break_statement','continue_statement'}:
            if children(n):self.fail('Labeled break/continue not implemented',n)
            if not self.loop_stack:self.fail('Loop jump outside loop',n)
            return ['goto '+self.loop_stack[-1][0 if k=='break_statement' else 1]]
        if k=='assert_statement':
            c=children(n)
            if len(c)!=1:self.fail('Java assert message expressions not implemented',n)
            e=self.expr(c[0])
            if e.typ!=BOOL:self.fail('assert needs boolean',n)
            return e.pre+['assert '+e.value]
        if k in {'empty_statement','line_comment','block_comment'}:return []
        self.fail('Unsupported statement: '+k,n)

    def falls_through(self,n):
        if n.type in {'return_statement','throw_statement'}:return False
        if n.type in {'block','constructor_body'}:
            live=True
            for c in children(n):
                if live:live=self.falls_through(c)
            return live
        if n.type=='if_statement':
            alt=n.child_by_field_name('alternative')
            return alt is None or self.falls_through(n.child_by_field_name('consequence')) or self.falls_through(alt)
        if n.type in {'while_statement','for_statement'}:
            cond=n.child_by_field_name('condition')
            if (cond is None or txt(cond).strip('() ')=='true') and not any(x.type=='break_statement' for x in walk(n)):return False
        return True

    def statement_expr(self,n):
        # Discarded values need no temporary; only simplify a local, side-effect-safe case.
        if n.type=='update_expression' and children(n)[0].type=='identifier':
            target=children(n)[0];lv=self.lvalue(target)
            if self.lookup(txt(target)):
                if lv.value not in self.assigned:self.fail('Increment reads uninitialized local',n)
                if lv.typ.base=='char' or not (lv.typ.integer or lv.typ.real):self.fail('Unsupported increment type',n)
                return [lv.value+' := '+lv.value+(' + ' if '++' in txt(n) else ' - ')+('write' if lv.typ.real else '1')]
        if n.type=='assignment_expression' and txt(n.child_by_field_name('operator'))=='=' and n.child_by_field_name('left').type=='identifier':
            lv=self.lvalue(n.child_by_field_name('left'));e=self.expr(n.child_by_field_name('right'),lv.typ)
            if self.lookup(txt(n.child_by_field_name('left'))):self.assigned.add(lv.value)
            return e.pre+[lv.store(self.convert(e,lv.typ,n))]
        e=self.expr(n)
        pre=list(e.pre)
        if n.type=='method_invocation' and e.typ!=VOID:self.fresh(e.typ,pre,e.value)
        return pre

    def loop(self,n):
        lid=self.current.key+f'/L{self.loop_count}';self.loop_count+=1
        label=f'_j_loop{self.loop_count}';end=label+'_end';cont=label+'_continue'
        self.scopes.append({});pre=[];update=[];lead=[];condition_update=[]
        if n.type=='for_statement':
            for init in n.children_by_field_name('init'):
                pre+=self.stmt(init) if init.type=='local_variable_declaration' else self.expr(init).pre
            # Updates are lowered after the body, so definite assignment follows Java flow.
        if n.type=='enhanced_for_statement':
            a=self.expr(n.child_by_field_name('value'))
            if not a.typ.dims:self.fail('Enhanced for only supports arrays',n)
            av=self.freeze(a,pre);idx=self.fresh(INT,pre,'0');f=self.field(a.typ)
            t=parse_type(n.child_by_field_name('type'));v=self.local(txt(n.child_by_field_name('name')),t,n)
            pre.append(f'var {v}: {t.silver}')
            self.assigned.add(v)
            lead=[f'{v} := {self.convert(Expr(av+"."+f+"["+idx+"]",a.typ.element),t,n)}']
            cond=Expr(f'{idx} < |{av}.{f}|',BOOL);update=[f'{idx} := {idx} + 1']
        elif n.type=='do_statement':
            gate=self.fresh(BOOL,pre,'true');c=self.expr(n.child_by_field_name('condition'))
            if c.typ!=BOOL:self.fail('Loop condition must be boolean',n)
            cond=Expr(gate,BOOL);update=c.pre+[f'{gate} := {c.value}']
        else:
            cn=n.child_by_field_name('condition');cond=self.expr(cn) if cn else Expr('true',BOOL)
        if cond.typ!=BOOL:self.fail('Loop condition must be boolean',n)
        # Side-effectful conditions are evaluated once before, then after each body/update.
        # Repeated declarations stay in separate lexical blocks; a stable gate is carried.
        if cond.pre:
            gate=self.fresh(BOOL,pre)
            evaluation=['{']+indent(cond.pre+[f'{gate} := {cond.value}'])+['}']
            pre+=evaluation;condition_update=evaluation;condition=gate
        else:condition=cond.value
        before=set(self.assigned)
        self.loop_stack.append((end,cont));body=lead+self.stmt(n.child_by_field_name('body'));self.loop_stack.pop()
        if n.type=='for_statement':
            for u in n.children_by_field_name('update'):update+=self.statement_expr(u)
        if any('goto '+cont==x.strip() for x in body):body.append('label '+cont)
        body+=update+condition_update
        cfg=self.spec.get('loops',{}).get(lid,{})
        inv=cfg.get('invariants',[])
        self.maps['loops'][lid]={'method':self.current.key,'source_line':n.start_point.row+1,'kind':n.type,
                                 'variables':{name:{'silver_name':v,'java_type':str(t)} for s in self.scopes for name,(v,t) in s.items()}}
        out=pre+['// loop '+lid,f'while ({condition})']+['  invariant '+x for x in inv]
        if cfg.get('decreases'):out+=['  decreases '+', '.join(cfg['decreases'])]
        out+=['{']+indent(body)+['}']
        if any('goto '+end==x.strip() for x in body):out.append('label '+end)
        self.assigned=before
        self.scopes.pop();return out

    def helpers(self):
        out=[]
        if 'nonnull' in self.runtime:out+=['function jnonnull(r: Ref): Bool requires r != null { true }','']
        if 'division' in self.runtime:
            out += ['function jabs(x: Int): Int { x < 0 ? -x : x }',
                    'function jdiv(x: Int, y: Int): Int', '  requires y != 0',
                    '{ (x < 0) != (y < 0) ? -(jabs(x) / jabs(y)) : jabs(x) / jabs(y) }',
                    'function jrem(x: Int, y: Int): Int', '  requires y != 0', '{ x - jdiv(x, y) * y }','']
        for t in ['Int','Bool','Perm']:
            if 'nd_'+t in self.runtime:out += [f'method nondet{t}() returns (value: {t})','']
        return out


